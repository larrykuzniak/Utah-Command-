const assert=require('node:assert/strict');
const D=require('../game/operational-data.js');
const friendly={id:'1/8',name:'1/8 Infantry',side:'us',type:'infantry',commandId:'hq-8',hp:6,stock:1,cohesion:75,x:4,y:3};
const enemy={id:'enemy',name:'Hidden enemy',side:'de',type:'infantry',hp:9,stock:3,x:2,y:1,order:{type:'attack'}};
const state={turn:3,scenarioId:'utah-division',weather:'rain',units:[{id:'hq-8',side:'us',type:'hq',hp:10},friendly,enemy]};
const one=D.snapshot(state,{viewer:'us'});
assert.equal(one.units.length,2);assert.equal(one.contacts.length,0);
assert.equal(JSON.stringify(one).includes('Hidden enemy'),false);
assert.equal(one.totals.lowSupply,1);
assert.equal(one.units.find(u=>u.id==='1/8').personnel.present,null);
const observed=D.snapshot(state,{viewer:'us',isVisible:u=>u.id==='enemy'});
assert.equal(observed.contacts.length,1);
assert.equal(JSON.stringify(observed).includes('Hidden enemy'),false);
assert.equal(JSON.stringify(observed).includes('"stock":3'),false);
const edited=JSON.parse(JSON.stringify(state));edited.units[1].stock=2;
const two=D.snapshot(edited,{viewer:'us'});
assert.deepEqual(D.diff(one,two),[{unitId:'1/8',kind:'change',field:'stock',before:1,after:2,turn:3}]);
assert.equal(state.units[1].stock,1);
assert.deepEqual(D.checkLedger({authorized:100,present:80,fit:60,killed:0,wounded:10,missing:5,temporarilyUnavailable:5,returnedToDuty:0,replacements:0}),[]);
assert(D.checkLedger({authorized:100,present:80,fit:90,killed:0,wounded:10,missing:5,temporarilyUnavailable:5,returnedToDuty:0,replacements:0}).length>0);
assert(D.snapshot({...state,units:[state.units[0],state.units[0]]}).errors.some(x=>x.includes('Duplicate')));
console.log('Operational data: schema, delta, fog-of-war, ledger and immutability checks passed');
